// Builds src/data/directory.ts from the K51 handbook directory (offices + faculties).
// Run from frontend/: npm run build:directory
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '..', '..', 'data', 'processed', 'directories');
const OUT = join(here, '..', 'src', 'data', 'directory.ts');
const readJson = (name) => JSON.parse(readFileSync(join(SRC, name), 'utf8'));

// Synonyms students type that the handbook wording does not contain.
const KEYWORDS = {
  'Phòng Khảo thí và Đảm bảo chất lượng': ['phúc khảo', 'điểm thi', 'bảng điểm', 'lịch thi', 'chứng chỉ'],
  'Phòng Kế hoạch – Tài chính': ['học phí', 'biên lai', 'hoàn học phí'],
  'Phòng Đào tạo': ['đăng ký học phần', 'học vụ', 'tốt nghiệp', 'chương trình đào tạo'],
  'Phòng Công tác chính trị và Học sinh, sinh viên': ['học bổng', 'rèn luyện', 'nghị định 116', 'miễn giảm', 'thẻ sinh viên'],
  'Phòng Công nghệ Thông tin': ['email', 'tài khoản', 'mật khẩu', 'wifi'],
  'Trạm Y tế': ['bảo hiểm', 'bhyt', 'khám sức khỏe'],
};

// Offices students contact most come first; the rest keep the handbook order.
const FIRST = [
  'Phòng Đào tạo',
  'Phòng Công tác chính trị và Học sinh, sinh viên',
  'Phòng Kế hoạch – Tài chính',
  'Phòng Khảo thí và Đảm bảo chất lượng',
  'Phòng Công nghệ Thông tin',
  'Ký túc xá',
  'Trạm Y tế',
  'Thư viện',
  'Trung tâm Hỗ trợ sinh viên và Phát triển khởi nghiệp',
  'Đoàn Thanh niên và Hội Sinh viên Trường',
];

const offices = readJson('student_office_profiles.json')
  .filter((x) => x.cohort === 'K51')
  .map((x) => ({
    name: x.unit_name,
    aliases: x.aliases,
    services: x.services,
    keywords: KEYWORDS[x.unit_name] ?? [],
    phones: x.phones,
    ext: x.internal_numbers,
    emails: x.emails,
    office: (x.offices || [''])[0] || '',
    web: (x.websites || [''])[0] || '',
  }));
const rank = (o) => (FIRST.includes(o.name) ? FIRST.indexOf(o.name) : 100);
offices.sort((a, b) => rank(a) - rank(b)); // stable

const faculties = [];
const seen = new Set();
for (const x of readJson('K51_faculty_directory.json')) {
  const text = x.raw_text;
  const name = x.faculty_or_unit_name.replace(/^\d+\.\s*/, '').trim();
  const phone = text.match(/\(0\d{2}\)\s*[\d ]+/);
  const ext = text.match(/nội bộ\s*:?\s*([\d, ]+)/);
  const email = text.match(/[\w.-]+@hcmue\.edu\.vn/);
  if (!email) continue;
  const mail = email[0];
  if (seen.has(mail)) continue; // same unit listed twice
  seen.add(mail);
  const campus = mail.startsWith('longan.') ? 'Phân hiệu Long An' : mail.startsWith('gialai.') ? 'Phân hiệu Gia Lai' : 'TP.HCM';
  const office = text.replace(/\n/g, ' ').match(/Văn phòng làm việc\s*:\s*(.+?)(?:\.\s|\.$|Những công việc|CÁC TỔ)/);
  faculties.push({
    name,
    campus,
    aliases: [],
    services: [],
    keywords: [],
    phones: phone ? [phone[0].replace(/\s+/g, ' ').trim()] : [],
    ext: ext ? ext[1].split(',').map((e) => e.trim()).filter(Boolean) : [],
    emails: [mail],
    office: office ? office[1].trim() : '',
    web: '',
  });
}

const literal = (list) => JSON.stringify(list, null, 2).replace(/"([a-z]+)":/g, '$1:');
const out = `// Generated by scripts/build-directory.mjs from the K51 handbook directory — do not edit by hand.

export interface DirectoryUnit {
  name: string;
  /** Campus label; only faculties carry it. */
  campus?: string;
  aliases: string[];
  services: string[];
  /** Words students type that the handbook wording does not contain. */
  keywords: string[];
  phones: string[];
  /** Internal extensions, dialled after the main number. */
  ext: string[];
  emails: string[];
  office: string;
  web: string;
}

export const DIRECTORY_SOURCE = 'Sổ tay sinh viên K51';

export const OFFICES: DirectoryUnit[] = ${literal(offices.map(({ ...o }) => o))};

export const FACULTIES: DirectoryUnit[] = ${literal(faculties)};
`;
writeFileSync(OUT, out, 'utf8');
console.log(`directory.ts: ${offices.length} offices, ${faculties.length} faculties`);
